#한줄에 우겨넣기
#------------------------------------------------------------------
#ex1)
#------------------------------------------------------------------
nums = []
for i in range(1, 10+1) :
    nums.append(3*i)
print(nums)
print()
#한줄로 정리
#------------------------------------------------------------------
nums = [3*i for i in range(1, 10+1)]
print(nums)
print()


